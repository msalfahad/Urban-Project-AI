"""CODE MAP - build or check docs/CODEMAP.md and docs/RULES_INDEX.md (where every module, rule and record lives).

    python3 -I tools/codemap.py           rebuild both maps
    python3 -I tools/codemap.py --check   exit 1 when either map is out of date (no file is written)

Read-only over the repository except for the two map files. Stdlib only. The output is deterministic (no dates, no
commit ids), so a map is stale only when the code or rules it describes changed. It moves, renames and edits nothing:
the maps are an index over the files where they already are, so frozen hashes and imports are untouched.
"""

from __future__ import annotations

