def tracked():
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files"], capture_output=True, text=True, check=True).stdout
    return sorted(p for p in out.splitlines() if p)


def first_line(text):
    for ln in text.strip().splitlines():
        ln = ln.strip().strip("#").strip()
        if ln:
            return ln.replace("|", "/")[:140]
    return ""


def py_info(path):
    src = (ROOT / path).read_text(encoding="utf-8", errors="replace")
    lines = src.count("\n") + 1
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return lines, "(does not parse)", []
    doc = first_line(ast.get_docstring(tree) or "")
    tops = [(n.lineno, ("class " if isinstance(n, ast.ClassDef) else "def ") + n.name)
            for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
            and not n.name.startswith("_")]
    return lines, doc, tops


def md_title(path):
    try:
        return first_line((ROOT / path).read_text(encoding="utf-8", errors="replace")[:2000])
    except OSError:
        return ""


def build_codemap(files):
    top = Counter(p.split("/")[0] for p in files if "/" in p)
    L = ["# Code map", "",
         "Generated by `tools/codemap.py`. Do not edit by hand: run `python3 -I tools/codemap.py` after adding, moving or",
         "renaming files, and `--check` to see whether this map is stale. Rules are indexed in `docs/RULES_INDEX.md`.", "",
         "How to use it: find the area below, open only that file, and Grep inside it for the symbol (big modules list",
         "their public classes and functions with line numbers). Never read `research/` unless the task is about a report.", "",
         "## Top-level folders", "", "| Folder | Tracked files | What lives there |", "|---|---|---|"]
    for d, n in sorted(top.items()):
        L.append(f"| `{d}/` | {n} | {PURPOSE.get(d, '')} |")

    for root in CODE_DIRS:
        mods = [p for p in files if p.startswith(root + "/") and p.endswith(".py") and not p.endswith("__init__.py")]
        groups = defaultdict(list)
        for p in mods:
            groups[p.rsplit("/", 1)[0]].append(p)
        for g in sorted(groups):
            L += ["", f"## `{g}/` ({len(groups[g])} modules)", "", "| Module | Lines | Purpose (first docstring line) |", "|---|---|---|"]
            bigs = []
            for p in sorted(groups[g]):
                n, doc, tops = py_info(p)
                L.append(f"| `{p.rsplit('/', 1)[1]}` | {n} | {doc} |")
                if n >= BIG and tops:
                    bigs.append((p, tops))
            for p, tops in bigs:
                L += ["", f"`{p}` public symbols: " + ", ".join(f"{name} (L{ln})" for ln, name in tops[:60])]

    agents = sorted({p.split("/")[1] for p in files if p.startswith("agents/a")})
    L += ["", "## `agents/`", "", "| Agent | Purpose |", "|---|---|"]
    for a in agents:
        doc = ""
        if (ROOT / f"agents/{a}/agent.py").exists():
            doc = py_info(f"agents/{a}/agent.py")[1]
        L.append(f"| `{a}` | {doc} |")

    tdirs = Counter(p.split("/")[1] if p.count("/") >= 2 else "(root)" for p in files
                    if p.startswith("tests/") and p.rsplit("/", 1)[-1].startswith("test_"))
    L += ["", "## `tests/` (test files per folder)", "", "| Folder | Test files |", "|---|---|"]
    L += [f"| `tests/{d}/` | {n} |" if d != "(root)" else f"| `tests/` (root) | {n} |" for d, n in sorted(tdirs.items())]

    docs = [p for p in files if p.startswith("docs/") and p.endswith(".md") and p not in ("docs/CODEMAP.md", "docs/RULES_INDEX.md", "docs/ROUTING.md")]
    L += ["", "## `docs/`", "", "| File | Title |", "|---|---|"]
    L += [f"| `{p[5:]}` | {md_title(p)} |" for p in docs]

    rs = Counter(p.split("/")[1] for p in files if p.startswith("research/") and p.count("/") >= 2)
    L += ["", "## `research/` (evidence folders, newest phases have the highest names)", "", "| Folder | Files |", "|---|---|"]
    L += [f"| `research/{d}/` | {n} |" for d, n in sorted(rs.items())]
    return "\n".join(L) + "\n"


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def cell(x, n=110):
    s = x if isinstance(x, str) else json.dumps(x, ensure_ascii=False)
    return s.replace("|", "/").replace("\n", " ")[:n]


def py_const(rel, name):
    m = re.search(rf"^{name}\s*=\s*(.+)$", (ROOT / rel).read_text(encoding="utf-8"), re.M)
    return m.group(1).strip() if m else "?"


