def svg_layout(case, area):
    """the area to scale: the floor strips of the selected layout (clipped to the room), the band runs on the
    eligible boundary, the doorways and open edges, dimensions in metres."""
    ring = case["scenario"]["ring"]
    lay = area["layout"]["layout"]
    xs, ys = [p[0] for p in ring], [p[1] for p in ring]
    x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)
    k = min(560 / (x1 - x0), 380 / (y1 - y0))
    pad = 50
    X = lambda x: pad + (x - x0) * k                                                    # noqa: E731
    Y = lambda y: pad + (y1 - y) * k                                                    # noqa: E731
    w, h = max(int((x1 - x0) * k + 2 * pad), 760), int((y1 - y0) * k + 2 * pad + 40)
    pts = " ".join(f"{X(x):.1f},{Y(y):.1f}" for x, y in ring)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
           f'font-family="Arial" font-size="11">',
           f'<rect width="{w}" height="{h}" fill="#ffffff"/>',
           f'<defs><clipPath id="room"><polygon points="{pts}"/></clipPath></defs>']
    along_x = lay["direction"] == "ALONG_X"
    n, wl = lay["floor_strips"], lay["last_strip_width_m"]
    pitch = 1.0 - case_lap(case)
    out.append('<g clip-path="url(#room)">')
    for i in range(n):
        a = i * pitch
        b = a + (1.0 if i < n - 1 else wl)
        if along_x:
            rx, ry, rw, rh = X(x0), Y(y0 + b), (x1 - x0) * k, (b - a) * k
        else:
            rx, ry, rw, rh = X(x0 + a), Y(y1), (b - a) * k, (y1 - y0) * k
        fill = "#9ecae1" if i % 2 == 0 else "#c6dbef"
        out.append(f'<rect x="{rx:.1f}" y="{ry:.1f}" width="{rw:.1f}" height="{rh:.1f}" fill="{fill}" '
                   f'fill-opacity="0.75" stroke="#3182bd" stroke-width="0.8"/>')
        cx, cy = (rx + rw / 2, ry + rh / 2)
        out.append(f'<text x="{cx:.1f}" y="{cy:.1f}" text-anchor="middle" fill="#08306b">S{i + 1} '
                   f'{fmt(1.0 if i < n - 1 else wl)}</text>')
    out.append('</g>')
    out.append(f'<polygon points="{pts}" fill="none" stroke="#252525" stroke-width="1.2"/>')
    # the band: eligible edges thick orange, doors / open edges marked
    gaps = [(d["edge"], d["t0"], d["t1"], "door " + d["id"]) for d in case["scenario"]["doors"]] + \
        [(e["edge"], e["t0"], e["t1"], "open edge " + e["id"]) for e in case["scenario"].get("open_edges", ())]
    for i in range(len(ring)):
        (ax, ay), (bx, by) = ring[i], ring[(i + 1) % len(ring)]
        L = ((bx - ax) ** 2 + (by - ay) ** 2) ** 0.5
        ux, uy = (bx - ax) / L, (by - ay) / L
        cuts = sorted((t0, t1, why) for e, t0, t1, why in gaps if e == i)
        pos = 0.0
        for t0, t1, why in cuts + [(L, L, None)]:
            if t0 > pos:
                out.append(f'<line x1="{X(ax + ux * pos):.1f}" y1="{Y(ay + uy * pos):.1f}" x2="{X(ax + ux * t0):.1f}" '
                           f'y2="{Y(ay + uy * t0):.1f}" stroke="#e6550d" stroke-width="5" stroke-opacity="0.7"/>')
            if why:
                mx, my = ax + ux * (t0 + t1) / 2, ay + uy * (t0 + t1) / 2
                out.append(f'<line x1="{X(ax + ux * t0):.1f}" y1="{Y(ay + uy * t0):.1f}" x2="{X(ax + ux * t1):.1f}" '
                           f'y2="{Y(ay + uy * t1):.1f}" stroke="#31a354" stroke-width="5" stroke-dasharray="4,3"/>')
                out.append(f'<text x="{X(mx):.1f}" y="{Y(my) - 8:.1f}" text-anchor="middle" fill="#006d2c">{why} '
                           f'{fmt(t1 - t0)} m</text>')
            pos = max(pos, t1)
        # the edge length just outside the wall (outward normal of a counter-clockwise ring)
        off = 16.0 / k
        lx, ly = (ax + bx) / 2 + uy * off, (ay + by) / 2 - ux * off
        out.append(f'<text x="{X(lx):.1f}" y="{Y(ly) + 4:.1f}" text-anchor="middle" fill="#525252" '
                   f'font-size="10">{fmt(L)} m</text>')
    for p in case["scenario"]["inserts"] + case["scenario"]["texts"]:
        out.append(f'<circle cx="{X(p["x"]):.1f}" cy="{Y(p["y"]):.1f}" r="5" fill="#756bb1"/>')
        out.append(f'<text x="{X(p["x"]) + 8:.1f}" y="{Y(p["y"]) + 4:.1f}" fill="#54278f">'
                   f'{p.get("name") or p.get("value")}</text>')
    r = area["row"]
    out.append(f'<text x="{pad}" y="{h - 22}" fill="#252525">{case["id"]}: {lay["direction"]}, {n} strips (last '
               f'{fmt(wl)} m), band {fmt(lay["band_width_m"])} m, pieces {fmt(sorted(lay["band_pieces_m"]))} m</text>')
    out.append(f'<text x="{pad}" y="{h - 8}" fill="#252525">A {fmt(r["A_net_horizontal_m2"])} m2, upturn '
               f'{fmt(r["upturn"]["area_m2"])} m2, B {fmt(r["B_installed_m2"])} m2, consumed {fmt(r["consumed_m2"])} '
               f'm2, {r["rolls_if_installed_alone"]} roll(s); orange = upturn band, green = doorway / open edge'
               f'</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def svg_rolls(title, rolls, L=10.0):
    """one bar per roll (L metres), each cut piece a segment with its length and purpose; the untouched remainder
    hatched (stock, not waste)."""
    k, pad, bar = 70.0, 20, 26
    w, h = int(L * k + 2 * pad + 160), int(pad * 2 + len(rolls) * (bar + 24) + 20)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
           f'font-family="Arial" font-size="10">', f'<rect width="{w}" height="{h}" fill="#ffffff"/>',
           '<defs><pattern id="hatch" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform='
           '"rotate(45)"><line x1="0" y1="0" x2="0" y2="6" stroke="#bdbdbd" stroke-width="2"/></pattern></defs>',
           f'<text x="{pad}" y="14" font-size="12" fill="#252525">{title}</text>']
    colours = {"floor": "#9ecae1", "upturn": "#fdae6b", "doorway": "#a1d99b", "patch": "#bcbddc"}
    for i, (name, pieces) in enumerate(rolls):
        y = pad + 10 + i * (bar + 24)
        out.append(f'<text x="{pad}" y="{y + bar / 2 + 4}" fill="#252525">{name}</text>')
        x = pad + 120
        for ln, why in pieces:
            col = next((v for k_, v in colours.items() if k_ in why), "#d9d9d9")
            out.append(f'<rect x="{x:.1f}" y="{y}" width="{ln * k:.1f}" height="{bar}" fill="{col}" '
                       f'stroke="#525252" stroke-width="0.8"/>')
            out.append(f'<text x="{x + ln * k / 2:.1f}" y="{y + bar / 2 + 4}" text-anchor="middle">{fmt(ln)}</text>')
            out.append(f'<text x="{x + ln * k / 2:.1f}" y="{y + bar + 11}" text-anchor="middle" font-size="8" '
                       f'fill="#525252">{why[:22]}</text>')
            x += ln * k
        rest = L - sum(p[0] for p in pieces)
        if rest > 1e-9:
            out.append(f'<rect x="{x:.1f}" y="{y}" width="{rest * k:.1f}" height="{bar}" fill="url(#hatch)" '
                       f'stroke="#525252" stroke-width="0.8"/>')
            out.append(f'<text x="{x + rest * k / 2:.1f}" y="{y + bar / 2 + 4}" text-anchor="middle" '
                       f'fill="#525252">{fmt(rest)} left</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def case_lap(case):
    return next((r["value"] for r in case["scenario"].get("rules") or () if r.get("parameter") == "lap_m"), 0.1)


