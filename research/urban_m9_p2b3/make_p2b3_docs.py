           "One sheet per case, in the sequence the cases are proven (a case is compared only when every simpler case "
           "passes). (1) scenario, (2) Urban rules, (3) project overrides, (4) the independent hand calculation, (5) "
           "its expected quantities, (6) - (8) the engine quantities, difference, tolerance and PASS / FAIL, (9) "
