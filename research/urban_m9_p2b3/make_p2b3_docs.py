        out += [f"{i + 1}. {s}\n" for i, s in enumerate(c["hand"])]
        ref = PC.hand_vs_reference(c)
        if ref:
            ok = sum(1 for r in ref if r["result"] == "AGREE")
            out.append(f"\nIndependent reference calculator (`proof_reference.py`, whole millimetres, exhaustive "
                       f"search): {ok} of {len(ref)} quantities agree with the hand calculation.\n\n")
