        if c["id"] == "WP-H":
            out.append("Members: " + ", ".join(c["members"]) + "\n\n**Hand calculation**\n\n")
            out += [f"{i + 1}. {s}\n" for i, s in enumerate(c["hand"])]
            res = results["WP-H"]
            out.append("\n" + table(res, ["quantity", "expected", "engine", "result"]) + "\n")
